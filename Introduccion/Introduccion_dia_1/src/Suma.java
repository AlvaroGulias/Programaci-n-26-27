public class Suma {

    static void main(String[] args) {
        int numero1 = 1; int numero2 = 2;
        int suma = numero1 + numero2;
        System.out.println(numero1 + " + " + numero2 + " = " + suma);
        System.out.println("La suma de " + numero1 + " + " + numero2 + " = " + (numero1 + numero2));
    }
}
