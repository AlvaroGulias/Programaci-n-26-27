public class Ejercicio9_Edades {

    static void main(String[] args) {

        byte edadJuan = 20;

        byte edadPedro = (byte) (edadJuan + 1);

        System.out.println("Edad de Juan: " + edadJuan + ", edad Pedro: " + edadPedro);


        short salarioJuan = 1980, salarioPedro = 800;

        short gananciasTotales = (short) (salarioJuan + salarioPedro);

        System.out.println("Salario total = " + gananciasTotales);


    }
}
